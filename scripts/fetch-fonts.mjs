/**
 * Self-host the typefaces used by the site.
 *
 * Google Fonts ships CJK families as many small unicode-range slices. Self-hosting
 * them keeps the blog fully offline-capable and lets the browser download only the
 * slices actually needed by the visible text.
 *
 *   node scripts/fetch-fonts.mjs
 *
 * Output: public/fonts/*.woff2 + src/styles/fonts.css
 */
import { mkdir, writeFile, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';

const OUT_DIR = path.resolve('public/fonts');
const CSS_OUT = path.resolve('src/styles/fonts.css');

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

const FAMILIES = [
  {
    slug: 'noto-serif-sc',
    query: 'Noto+Serif+SC:wght@400;500;700',
  },
  {
    slug: 'eb-garamond',
    query: 'EB+Garamond:ital,wght@0,400;0,500;1,400;1,500',
  },
  {
    slug: 'jetbrains-mono',
    query: 'JetBrains+Mono:wght@400;500',
  },
];

async function fetchText(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return res.text();
}

function parseFaces(css) {
  const faces = [];
  const blocks = css.match(/@font-face\s*\{[^}]*\}/g) || [];
  for (const block of blocks) {
    const get = (prop) => {
      const m = block.match(new RegExp(`(?:^|\\n|;)\\s*${prop}:\\s*([^;]+);`));
      return m ? m[1].trim() : '';
    };
    const family = (get('font-family') || '').replace(/^['"]|['"]$/g, '');
    const style = get('font-style') || 'normal';
    const weight = get('font-weight') || '400';
    const range = get('unicode-range');
    const srcMatch = block.match(/url\(([^)]+)\)/);
    if (!family || !srcMatch) continue;
    faces.push({ family, style, weight, range, url: srcMatch[1].replace(/^['"]|['"]$/g, '') });
  }
  return faces;
}

async function download(url, slug, seen) {
  if (seen.has(url)) return seen.get(url);
  const buf = Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer());
  const hash = createHash('sha1').update(url).digest('hex').slice(0, 8);
  const name = `${slug}-${hash}.woff2`;
  await writeFile(path.join(OUT_DIR, name), buf);
  const publicPath = `/fonts/${name}`;
  seen.set(url, publicPath);
  return publicPath;
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  await mkdir(path.dirname(CSS_OUT), { recursive: true });

  const seen = new Map();
  const rules = [];
  let bytes = 0;
  let files = 0;
  const started = Date.now();

  for (const fam of FAMILIES) {
    const cssUrl = `https://fonts.googleapis.com/css2?family=${fam.query}&display=swap`;
    const css = await fetchText(cssUrl);
    const faces = parseFaces(css);
    if (!faces.length) throw new Error(`no @font-face found for ${fam.slug}`);

    for (const face of faces) {
      const localPath = await download(face.url, fam.slug, seen).catch((err) => {
        console.warn(`  ! ${face.url}: ${err.message}`);
        return null;
      });
      if (!localPath) continue;
      files += 1;
      const name = face.style === 'italic' ? `'${face.family}'` : `'${face.family}'`;
      rules.push(
        `@font-face{font-family:${name};font-style:${face.style};font-weight:${face.weight};font-display:swap;` +
          `src:url(${localPath}) format('woff2');` +
          (face.range ? `unicode-range:${face.range};` : '') +
          `}`,
      );
    }
    console.log(`${fam.slug}: ${faces.length} slices`);
  }

  const header =
    '/* AUTO-GENERATED by scripts/fetch-fonts.mjs — do not edit by hand. */\n' +
    `/* ${files} slices, ${(bytes / 1024).toFixed(0)} KB */\n`;
  await writeFile(CSS_OUT, header + rules.join('\n') + '\n', 'utf8');

  let total = 0;
  for (const file of await import('node:fs/promises').then((m) => m.readdir(OUT_DIR))) {
    total += (await stat(path.join(OUT_DIR, file))).size;
  }
  console.log(
    `done in ${((Date.now() - started) / 1000).toFixed(1)}s — ${files} @font-face rules, ${(total / 1048576).toFixed(1)} MB on disk`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
